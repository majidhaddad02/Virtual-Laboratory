#!/usr/bin/env node
'use strict';

var fs = require('fs');
var path = require('path');
var vm = require('vm');

var ROOT = path.join(__dirname, '..');
var OUT = path.join(ROOT, 'data/registry.js');
var HEADER = '// GENERATED by tools/build-registry.js - do not edit\n';

function listSimIds() {
  var dir = path.join(ROOT, 'sims');
  var names = fs.readdirSync(dir);
  var out = [];
  var i, id, meta;
  for (i = 0; i < names.length; i++) {
    id = names[i];
    meta = path.join(dir, id, 'meta.js');
    if (fs.existsSync(meta) && fs.statSync(path.join(dir, id)).isDirectory()) out.push(id);
  }
  out.sort();
  return out;
}

function loadTopics() {
  var context = { window: {} };
  context.window = context;
  vm.createContext(context);
  var code = fs.readFileSync(path.join(ROOT, 'data/topics.js'), 'utf8');
  vm.runInContext(code, context, { filename: 'data/topics.js' });
  return (context.PL && context.PL.topics) || [];
}

function loadMeta(id) {
  var context = { window: {} };
  context.window = context;
  vm.createContext(context);
  var rel = 'sims/' + id + '/meta.js';
  var code = fs.readFileSync(path.join(ROOT, rel), 'utf8');
  vm.runInContext(code, context, { filename: rel });
  if (!context.PL || !context.PL.meta || !context.PL.meta[id]) {
    throw new Error('meta did not assign PL.meta[\'' + id + '\']');
  }
  return context.PL.meta[id];
}

function isStringArray(v) {
  if (!Array.isArray(v)) return false;
  var i;
  for (i = 0; i < v.length; i++) if (typeof v[i] !== 'string') return false;
  return true;
}

function validate(entry, topics, ids, errors) {
  var required = ['id', 'title', 'topics', 'level', 'goals', 'modelNotes', 'status', 'version', 'order', 'path'];
  var i, t;
  var topicIds = {};
  for (i = 0; i < topics.length; i++) topicIds[topics[i].id] = true;
  for (i = 0; i < required.length; i++) {
    if (entry[required[i]] == null) errors.push(entry.id + ': missing ' + required[i]);
  }
  if (ids[entry.id]) errors.push('duplicate id ' + entry.id);
  ids[entry.id] = true;
  if (!Array.isArray(entry.topics)) errors.push(entry.id + ': topics must be an array');
  else {
    for (i = 0; i < entry.topics.length; i++) {
      t = entry.topics[i];
      if (!topicIds[t]) errors.push(entry.id + ': unknown topic ' + t);
    }
  }
  if (!isStringArray(entry.goals) || entry.goals.length < 1) errors.push(entry.id + ': goals must be a non-empty string array');
  if (!isStringArray(entry.modelNotes)) errors.push(entry.id + ': modelNotes must be a string array');
  if (typeof entry.order !== 'number') errors.push(entry.id + ': order must be a number');
  if (entry.path && !fs.existsSync(path.join(ROOT, entry.path))) errors.push(entry.id + ': missing path ' + entry.path);
  if (entry.tags != null && !isStringArray(entry.tags)) errors.push(entry.id + ': tags must be a string array');
  if (entry.curriculum != null) {
    if (typeof entry.curriculum !== 'object' || Array.isArray(entry.curriculum)) {
      errors.push(entry.id + ': curriculum must be an object');
    } else {
      if (entry.curriculum.grade != null && typeof entry.curriculum.grade !== 'string') {
        errors.push(entry.id + ': curriculum.grade must be a string');
      }
      if (entry.curriculum.chapter != null && typeof entry.curriculum.chapter !== 'string') {
        errors.push(entry.id + ': curriculum.chapter must be a string');
      }
    }
  }
  if (typeof entry.thumbnail !== 'string' || entry.thumbnail.indexOf('<svg') !== 0) {
    errors.push(entry.id + ': thumbnail must start with "<svg"');
  }
}

function build() {
  var topics = loadTopics();
  var ids = {};
  var errors = [];
  var simIds = listSimIds();
  var registry = [];
  var i, id, meta, entry, thumbPath, thumb;
  for (i = 0; i < simIds.length; i++) {
    id = simIds[i];
    meta = loadMeta(id);
    thumbPath = path.join(ROOT, 'sims', id, 'thumb.svg');
    if (!fs.existsSync(thumbPath)) {
      errors.push(id + ': missing thumb.svg');
      thumb = '';
    } else {
      thumb = fs.readFileSync(thumbPath, 'utf8').replace(/^\uFEFF/, '').trim();
    }
    entry = {
      id: meta.id,
      title: meta.title,
      topics: meta.topics,
      level: meta.level,
      goals: meta.goals,
      modelNotes: meta.modelNotes,
      status: meta.status,
      version: meta.version,
      order: meta.order,
      thumbnail: thumb,
      path: meta.path
    };
    validate(entry, topics, ids, errors);
    registry.push(entry);
  }
  registry.sort(function (a, b) { return a.order - b.order; });
  var body = HEADER + '(function (PL) {\n  PL.registry = ' + JSON.stringify(registry, null, 2).split('\n').join('\n  ') + ';\n})(window.PL = window.PL || {});\n';
  return { code: body, registry: registry, errors: errors };
}

function write() {
  var result = build();
  if (result.errors.length) {
    console.error(result.errors.join('\n'));
    process.exit(1);
  }
  fs.writeFileSync(OUT, result.code);
  return result;
}

function check() {
  var result = build();
  if (result.errors.length) {
    console.error(result.errors.join('\n'));
    process.exitCode = 1;
    return result;
  }
  var current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (current !== result.code) {
    console.error('run npm run build-registry');
    process.exitCode = 1;
  }
  return result;
}

function main() {
  if (process.argv.indexOf('--check') !== -1) {
    check();
    if (process.exitCode) process.exit(process.exitCode);
    return;
  }
  write();
}

if (require.main === module) main();

module.exports = { build: build, write: write, check: check };
